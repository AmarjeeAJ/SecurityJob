export function getSubdivisionsForDistrict(state = '', district = '') {
  if (!district) return [];
  const cleanDistrict = district.trim();
  const exact = SUBDIVISION_BLOCK_MAP[cleanDistrict];
  if (exact) {
    return Object.keys(exact);
  }

  const lowerDist = cleanDistrict.toLowerCase();
  for (const [dKey, sObj] of Object.entries(SUBDIVISION_BLOCK_MAP)) {
    if (dKey.toLowerCase() === lowerDist || dKey.toLowerCase().includes(lowerDist) || lowerDist.includes(dKey.toLowerCase())) {
      return Object.keys(sObj);
    }
  }

  // Natural administrative subdivision fallback
  return [
    `${cleanDistrict} सदर (Sadar)`,
    `${cleanDistrict} ग्रामीण (Rural / North)`
  ];
}

/**
 * Get Blocks for a Subdivision and District
 */
export function getBlocksForSubdivision(state = '', district = '', subdivision = '') {
  if (!district) return [];
  const cleanDistrict = district.trim();
  const cleanSub = (subdivision || '').trim();

  let sObj = SUBDIVISION_BLOCK_MAP[cleanDistrict];
  if (!sObj) {
    const lowerDist = cleanDistrict.toLowerCase();
    for (const [dKey, val] of Object.entries(SUBDIVISION_BLOCK_MAP)) {
      if (dKey.toLowerCase() === lowerDist || dKey.toLowerCase().includes(lowerDist) || lowerDist.includes(dKey.toLowerCase())) {
        sObj = val;
        break;
      }
    }
  }

  if (sObj) {
    if (cleanSub) {
      if (sObj[cleanSub]) {
        return sObj[cleanSub];
      }
      const lowerSub = cleanSub.toLowerCase().replace(/[^a-z0-9]/g, '');
      for (const [sKey, bList] of Object.entries(sObj)) {
        const lowerKey = sKey.toLowerCase().replace(/[^a-z0-9]/g, '');
        if (lowerKey === lowerSub || lowerKey.includes(lowerSub) || lowerSub.includes(lowerKey)) {
          return bList;
        }
      }
    }

    // Return all blocks for the district if subdivision is not selected yet
    const all = [];
    for (const bList of Object.values(sObj)) {
      all.push(...bList);
    }
    return [...new Set(all)];
  }

  // Fallback to district tehsils
  return getTehsilsForDistrict(state, district);
}

/**
 * Auto-resolve PIN code based on District, Block / Subdivision, and Village
 * Exact and safe matching to avoid cross-district mismatching.
 */
export function getPincodeForLocation(district = '', block = '', village = '') {
  const normalize = (s) => (s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const bNorm = normalize(block);
  const vNorm = normalize(village);
  const dNorm = normalize(district);

  if (!dNorm && !bNorm) return '';

  // 1. Try `${district}:${block}`
  if (dNorm && bNorm) {
    const fullKey = `${dNorm}:${bNorm}`;
    if (BLOCK_PINCODE_MAP[fullKey]) {
      return BLOCK_PINCODE_MAP[fullKey];
    }
    // Search with exact word boundary / token match
    for (const [k, pin] of Object.entries(BLOCK_PINCODE_MAP)) {
      if (k.startsWith(`${dNorm}:`)) {
        const blkPart = k.split(':')[1];
        if (blkPart === bNorm || blkPart.includes(bNorm) || bNorm.includes(blkPart)) {
          return pin;
        }
      }
    }
  }

  // 2. Try `${district}:${village}`
  if (dNorm && vNorm) {
    const fullKey = `${dNorm}:${vNorm}`;
    if (BLOCK_PINCODE_MAP[fullKey]) {
      return BLOCK_PINCODE_MAP[fullKey];
    }
    for (const [k, pin] of Object.entries(BLOCK_PINCODE_MAP)) {
      if (k.startsWith(`${dNorm}:`)) {
        const blkPart = k.split(':')[1];
        if (blkPart === vNorm || blkPart.includes(vNorm) || vNorm.includes(blkPart)) {
          return pin;
        }
      }
    }
  }

  // 3. Try exact block match in map (only exact or strong match, never cross-district substring)
  if (bNorm) {
    for (const [k, pin] of Object.entries(BLOCK_PINCODE_MAP)) {
      const part = k.includes(':') ? k.split(':')[1] : k;
      if (part === bNorm) {
        return pin;
      }
    }
  }

  // 4. Try district head office PIN code if matched
  if (dNorm) {
    const distKey = `${dNorm}:${dNorm}`;
    if (BLOCK_PINCODE_MAP[distKey]) {
      return BLOCK_PINCODE_MAP[distKey];
    }
  }

  return '';
}
