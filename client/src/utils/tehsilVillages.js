/**
 * Get Tehsils / Blocks for a District
 */
export function getTehsilsForDistrict(state = '', district = '') {
  if (!district) return [];
  const cleanDistrict = district.trim();

  // 1. Check SUBDIVISION_BLOCK_MAP
  const subMap = SUBDIVISION_BLOCK_MAP[cleanDistrict];
  if (subMap) {
    const all = [];
    for (const bList of Object.values(subMap)) {
      all.push(...bList);
    }
    return [...new Set(all)];
  }

  // 2. Check DISTRICT_HIERARCHY_DATA
  const dObj = DISTRICT_HIERARCHY_DATA[cleanDistrict];
  if (dObj) {
    return Object.keys(dObj);
  }

  // 3. Fallback
  return [
    `${cleanDistrict} सदर (Sadar)`,
    `${cleanDistrict} ग्रामीण (Rural)`,
    `${cleanDistrict} उत्तर (North)`,
    `${cleanDistrict} दक्षिण (South)`,
    `${cleanDistrict} इंडस्ट्रियल एरिया (Industrial Area)`
  ];
}

/**
 * Get Villages for Tehsil / Block
 */
export function getVillagesForTehsil(state = '', district = '', tehsil = '') {
  if (!district) return [];
  const cleanDistrict = district.trim();
  const cleanTehsil = (tehsil || '').trim();

  let dObj = DISTRICT_HIERARCHY_DATA[cleanDistrict];
  if (!dObj) {
    const lowerDist = cleanDistrict.toLowerCase();
    for (const [dKey, val] of Object.entries(DISTRICT_HIERARCHY_DATA)) {
      if (dKey.toLowerCase() === lowerDist || dKey.toLowerCase().includes(lowerDist) || lowerDist.includes(dKey.toLowerCase())) {
        dObj = val;
        break;
      }
    }
  }

  if (dObj) {
    if (cleanTehsil) {
      if (dObj[cleanTehsil]) {
        return dObj[cleanTehsil];
      }

      const lowerTeh = cleanTehsil.toLowerCase().replace(/[^a-z0-9]/g, '');
      for (const [tKey, vList] of Object.entries(dObj)) {
        const lowerKey = tKey.toLowerCase().replace(/[^a-z0-9]/g, '');
        if (lowerKey === lowerTeh || lowerKey.includes(lowerTeh) || lowerTeh.includes(lowerKey)) {
          return vList;
        }
      }
    }

    const allVillages = [];
    for (const vList of Object.values(dObj)) {
      allVillages.push(...vList);
    }
    return [...new Set(allVillages)].slice(0, 50);
  }

  if (cleanTehsil) {
    return [
      `${cleanTehsil} मुख्य कस्बा / टाउन`,
      `${cleanTehsil} मेन मार्केट / बस स्टैंड`,
      `${cleanTehsil} ग्राम पंचायत`,
      `${cleanTehsil} वार्ड नं. 1 से 10`,
      `${cleanTehsil} इंडस्ट्रियल एरिया`
    ];
  }

  return [
    `${cleanDistrict} मुख्य शहर / टाउन`,
    `${cleanDistrict} सिविल लाइन्स`,
    `${cleanDistrict} स्टेशन रोड`,
    `${cleanDistrict} रीको / इंडस्ट्रियल एरिया`,
    `${cleanDistrict} मेन बस स्टैंड एरिया`
  ];
}

