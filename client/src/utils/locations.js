/**
 * Get districts for any selected state
 */
export function getDistrictsForState(state) {
  if (!state) return RAJASTHAN_CITIES;
  return STATE_DISTRICTS_DATA[state] || STATE_DISTRICTS_DATA['Rajasthan'] || RAJASTHAN_CITIES;
}

/**
 * Get tehsils or sub-districts for a given district
 */
export function getTehsilsForDistrict(district) {
  if (!district) return DISTRICT_TEHSILS_DATA['Jaipur'];
  if (DISTRICT_TEHSILS_DATA[district]) return DISTRICT_TEHSILS_DATA[district];

  // Try matching clean name
  const clean = district.trim().toLowerCase();
  const matchedKey = Object.keys(DISTRICT_TEHSILS_DATA).find(
    (k) => k.toLowerCase() === clean || clean.includes(k.toLowerCase())
  );
  if (matchedKey) return DISTRICT_TEHSILS_DATA[matchedKey];

  // Fallback: extract from smart areas
  const smartAreas = getSmartAreasForDistrict(district);
  if (smartAreas && smartAreas.length > 0) {
    return smartAreas.map((a) => a.split(' ')[0].replace(/[,()&]/g, '')).filter(Boolean).slice(0, 12);
  }

  return ['Central / City Tehsil', 'North / Industrial Tehsil', 'South / Rural Tehsil', 'Sub-District Area'];
}

/**
 * Intelligent helper to get top smart areas for any selected Rajasthan district or industrial hub
 */
export function getSmartAreasForDistrict(district) {
  if (!district) return RAJASTHAN_LOCATIONS_DATA['Jaipur'];
  const clean = district.trim().toLowerCase();

  // 1. Direct match
  const directKey = Object.keys(RAJASTHAN_LOCATIONS_DATA).find(
    (d) => d.toLowerCase() === clean
  );
  if (directKey) return RAJASTHAN_LOCATIONS_DATA[directKey];

  // 2. Specific alias mappings
  if (clean.includes('bhiwadi')) return RAJASTHAN_LOCATIONS_DATA['Bhiwadi'];
  if (clean.includes('neemrana')) return RAJASTHAN_LOCATIONS_DATA['Neemrana'];
  if (clean.includes('beawar')) return RAJASTHAN_LOCATIONS_DATA['Beawar'];
  if (clean.includes('balotra')) return RAJASTHAN_LOCATIONS_DATA['Balotra'];
  if (clean.includes('kotputli') || clean.includes('behror')) return RAJASTHAN_LOCATIONS_DATA['Kotputli-Behror'];
  if (clean.includes('khairthal') || clean.includes('tijara')) return RAJASTHAN_LOCATIONS_DATA['Khairthal-Tijara'];
  if (clean.includes('didwana') || clean.includes('kuchaman')) return RAJASTHAN_LOCATIONS_DATA['Didwana-Kuchaman'];
  if (clean.includes('phalodi')) return RAJASTHAN_LOCATIONS_DATA['Phalodi'];
  if (clean.includes('alwar')) return RAJASTHAN_LOCATIONS_DATA['Alwar'];

  // 3. Partial substring match
  const partialKey = Object.keys(RAJASTHAN_LOCATIONS_DATA).find(
    (d) => clean.includes(d.toLowerCase()) || d.toLowerCase().includes(clean)
  );
  if (partialKey) return RAJASTHAN_LOCATIONS_DATA[partialKey];

  // 4. Default fallback to Jaipur
  return RAJASTHAN_LOCATIONS_DATA['Jaipur'];
}

/**
 * Smart search to match areas based on partial text
 */
export function smartSearchAreas(district, query) {
  const areas = getSmartAreasForDistrict(district);
  if (!query || !query.trim()) return areas;
  const q = query.trim().toLowerCase();
  return areas.filter((a) => a.toLowerCase().includes(q));
}

